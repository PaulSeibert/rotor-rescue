#!/usr/bin/env python3
"""World 3 (Highlands, missions 7-9): the display art on the floppy (SPEC 13, docs/STYLE-world3.md).

Reads the CURRENT outputs of the art pass (the style branch's `art/world3/tools`: palettes `w3lib.MISSIONS`, the terrain
tile bank and fills `w3tiles`, the column planner `w3compose.Terrain`, the far range `w3compose.far_band`, the BOBs `w3bobs`)
and writes, for the game:
  disk/world3.bin     the parts one after another (8-byte aligned), loaded into the shared world arena at the world card
  src/world3_art.h    offsets, sizes and the per-mission palettes and gradients
  src/world3_map.h    the pilot's height map (heights at the 16 px joints, pad flags): logic.c's terrain

New art drops in: point `--art` at a different `art/world3` (default: this repo's, else the style worktree) and run again;
`--check` exits 1 when disk/ or src/ is stale. Needs Windows Python with Pillow and numpy (as the art tools).
"""
import os
import struct
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, "..", ".."))
STYLE_WTS = [os.path.join(os.path.expanduser("~"), "games", "first-w3style", "art", "world3"),
             "//wsl.localhost/Ubuntu-24.04/home/amiga/games/first-w3style/art/world3"]


def find_art(argv):
    if "--art" in argv:
        return os.path.abspath(argv[argv.index("--art") + 1])
    mine = os.path.join(root, "art", "world3")
    if os.path.isdir(os.path.join(mine, "tools")):
        return mine
    for p in STYLE_WTS:
        if os.path.isdir(os.path.join(p, "tools")):
            return p
    raise SystemExit("make_world3_disk: no art/world3 (pass --art DIR)")


def load_art(art):
    sys.path.insert(0, os.path.join(art, "tools"))
    import w3lib  # noqa: E402
    return w3lib


def hexes(vals, width=3):
    return ", ".join(f"0x{v:0{width}X}" for v in vals)


def palettes_header(L):
    out = []
    ms = L.MISSIONS
    def pal(name, key):
        out.append(f"static const uint16_t {name}[3][8] = {{")
        for m in ms:
            out.append("\t{0x000, " + hexes(m[key]) + "},")
        out.append("};")
    pal("g_pW3FarPal", "far")
    pal("g_pW3StripPal", "strip")
    pal("g_pW3CeilPal", "ceil")
    out.append("static const uint16_t g_pW3SkyDotPal[3][3] = {" + ", ".join("{" + hexes(m["dots"]) + "}" for m in ms) + "};")
    out.append("static const uint16_t g_pW3SkyTop[3] = {" + hexes([m["sky_top"] for m in ms]) + "};")
    out.append("static const uint16_t g_pW3SkyH[3] = {" + hexes([m["H"] for m in ms]) + "};")
    out.append("static const uint16_t g_pW3SkyV[3] = {" + hexes([m["V"] for m in ms]) + "};")
    out.append("static const uint32_t g_pW3SkyTop24[3] = {" + ", ".join("0x" + m["aga"][0] for m in ms) + "};")
    out.append("static const uint32_t g_pW3SkyH24[3] = {" + ", ".join("0x" + m["aga"][1] for m in ms) + "};")
    out.append("static const uint32_t g_pW3SkyV24[3] = {" + ", ".join("0x" + m["aga"][2] for m in ms) + "};")
    return "\n".join(out)


def header(L, world=""):
    return ("// Generated by art/tools/make_world3_disk.py from art/world3/ - do not edit.\n"
            "// World 3 (Highlands, missions 7-9): the per-mission palettes (STYLE-world3 section 3) and the display art's layout\n"
            "// (disk/world3.bin: the parts one after another; loaded into the world arena at the world card).\n"
            "#ifndef _WORLD3_ART_H_\n#define _WORLD3_ART_H_\n\n#include <stdint.h>\n\n"
            + world + "\n\n" + palettes_header(L) + "\n\n#endif // _WORLD3_ART_H_\n")


PILOT_COLS = 256          # the pilot map: 4096 px (W3_W); the art's M7 scene is its first 80 columns, then the land runs out flat
PEAK = 100


def pilot_terrain(art):
    """The pilot's column plan: the style pass's own M7 scene (its polyline, its forced benches, its seed), extended to 256 columns.
    -> (Terrain, objects of the scene). Keeping the art's planner means new art or a new M7 line drops in on the next run."""
    sys.path.insert(0, os.path.join(art, "tools"))
    import w3compose as C   # noqa: E402
    import w3scenes as S    # noqa: E402
    sc = S.build(0, with_far=False)
    t0 = sc["terrain"]
    pts = list(t0.pts)
    x1, y1 = pts[-1]
    for dx, y in ((120, 226), (220, 236)):          # down to the lowest ground, then flat to the end
        pts.append((x1 + dx, y))
    pts.append((PILOT_COLS * 16 + 64, 236))
    ter = C.Terrain(t0.M, pts, t0.forced, ncols=PILOT_COLS, seed=t0.seed, pines=t0.pines)
    return ter, sc["objects"]


def map_header(ter, objects, L):
    GY = L.GROUND_Y
    heights = []
    for c in ter.cols:
        heights.append(max(0, min(PEAK, GY - c["yl"])))
    last = ter.cols[-1]
    heights.append(max(0, min(PEAK, GY - last["yr"])))
    flags = [0] * PILOT_COLS
    pads = [o for o in objects if o["kind"] == "pad"]
    for o in pads:
        for c in range(o["x"] // 16, (o["x"] + o["w"]) // 16):
            flags[c] |= 1
    out = ["// Generated by art/tools/make_world3_disk.py from art/world3/ (the M7 scene's column plan) - do not edit.",
           "// World 3's pilot map: the surface height (px above GROUND_Y) at each 16 px joint, a flag a column (bit 0: a pad bed),",
           "// and the scenery (left edge x, in world px).",
           "#ifndef _WORLD3_MAP_H_", "#define _WORLD3_MAP_H_", "", "#include <stdint.h>", ""]
    pad = pads[0]
    out.append("#define W3_START_X %d      // the chopper's start: the middle of the first pad" % (pad["x"] + pad["w"] // 2))
    for o in objects:
        if o["kind"] in ("pad", "nest", "lodge"):
            out.append("#define W3_%s_X %d" % (o["kind"].upper(), o["x"]))
    out.append("#define W3_PAD_W %d" % pad["w"])
    out.append("static const uint8_t g_pW3Height[%d] = {" % (PILOT_COLS + 1))
    for i in range(0, len(heights), 16):
        out.append("\t" + ", ".join(str(v) for v in heights[i:i + 16]) + ",")
    out.append("};")
    out.append("static const uint8_t g_pW3Flags[%d] = {" % PILOT_COLS)
    for i in range(0, len(flags), 32):
        out.append("\t" + ", ".join(str(v) for v in flags[i:i + 32]) + ",")
    out.append("};")
    out.append("")
    out.append("#endif // _WORLD3_MAP_H_")
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------------------------------------ the world file
STRIP_ROWS = 126          # the ring: lines 130-255
FAR_W, FAR_LOOP, FAR_H = 640, 320, 42   # the far range: a 320 px loop stored twice (a fetch of 336 px starts anywhere in the first loop)
PAD_W, PAD_ROWS = 64, 46  # the pilot's pad: world 2's kit composed to 64 px (the skill-3 width)


def planar_rows(pens, wbytes_total=None):
    """pens: (rows, w) uint8, w a multiple of 8 -> bytes, a row at a time: plane 0's row, plane 1's, plane 2's (interleaved, as agk's converter)"""
    import numpy as np
    rows, w = pens.shape
    out = bytearray()
    for r in range(rows):
        for pl in range(3):
            bits = ((pens[r] >> pl) & 1).astype(np.uint8)
            out += np.packbits(bits).tobytes()
    return bytes(out)


def mask_rows(pens):
    import numpy as np
    rows, w = pens.shape
    out = bytearray()
    for r in range(rows):
        m = np.packbits((pens[r] > 0).astype(np.uint8)).tobytes()
        out += m * 3
    return bytes(out)


def pad_to_words(a):
    import numpy as np
    rows, w = a.shape
    w2 = (w + 15) // 16 * 16
    if w2 == w:
        return a
    b = np.zeros((rows, w2), np.uint8)
    b[:, :w] = a
    return b


def build_world(art, L, ter):
    """-> (bytes of disk/world3.bin, {name: (offset, bytes)}, facts). The parts one after another, each 8-byte aligned."""
    import numpy as np
    sys.path.insert(0, os.path.join(art, "tools"))
    import w3compose as C   # noqa: E402
    import w3tiles as T     # noqa: E402
    import w3bobs as BO     # noqa: E402
    parts = []
    facts = {}

    def add(name, data):
        pad = (-sum(len(d) for _, d in parts)) % 8
        if pad:
            parts.append(("pad_" + name, b"\0" * pad))
        parts.append((name, data))

    # the far range: M7's, a 320 px loop stored twice (its pens are the same in every mission; the palette differs)
    far = C.far_band(L.MISSIONS[0])
    assert far.shape == (FAR_H, 320)
    far2 = np.concatenate([far, far], axis=1)
    add("far", planar_rows(far2))

    # the tile bank (the columns the plan uses, in the art's own order), each tile's rows a word wide, 6 bytes a row
    bank, fills = ter.bank, ter.fills
    used = sorted({id(col["tile"]) for col in ter.cols}, key=lambda i: [id(t) for t in bank].index(i))
    tiles = [t for t in bank if id(t) in used]
    if len(bank) > 40:
        raise SystemExit("make_world3_disk: more than 40 top tiles in the bank (SPEC 13.4)")
    tab, blob, off = bytearray(), bytearray(), 0
    index = {}
    for i, t in enumerate(tiles):
        arr = t["arr"]
        index[id(t)] = i
        tab += struct.pack(">HBB", off, arr.shape[0], 0)
        data = planar_rows(arr.astype(np.uint8))
        blob += data
        off += len(data)
    add("tiletab", bytes(tab))
    add("tiles", bytes(blob))
    fb = bytearray()
    for fam, v, arr in fills:
        fb += planar_rows(arr.astype(np.uint8))
    add("fills", bytes(fb))

    # the column plan: tile, fill, the tile's top row in the ring; checked against the art's own raster below
    plan = bytearray()
    prev = 0
    sim = np.zeros((STRIP_ROWS, PILOT_COLS * 16), np.uint8)
    for c, col in enumerate(ter.cols):
        t = col["tile"]
        arr = t["arr"]
        r0 = col["Y"] - L.STRIP_Y
        d = col["d"]
        if t["name"].find("bench") >= 0 or t["name"].find("spike") >= 0 or t["name"].find("notch") >= 0:
            fam = "F"
        else:
            fam = "L" if d > 0 else "R" if d < 0 else "F"
        if prev > 0 and d < 0:
            fam = "LR"
        elif prev < 0 and d > 0:
            fam = "RL"
        prev = d if d != 0 else prev
        opts = [(i, f) for i, f in enumerate(fills) if f[0] == fam]
        fi = opts[int(L.hash01(c, ter.seed, 7) * len(opts)) % len(opts)][0]
        if not 0 <= r0 < STRIP_ROWS:
            raise SystemExit("make_world3_disk: column %d's tile starts at ring row %d (rows 0-5 are sky: lower the line)" % (c, r0))
        plan += bytes([index[id(t)], fi, r0])
        # simulate the three blits (clear above, the tile, the fill below) and compare with the art's raster
        x0 = c * 16
        rows = min(arr.shape[0], STRIP_ROWS - r0)
        sim[:r0, x0:x0 + 16] = 0
        sim[r0:r0 + rows, x0:x0 + 16] = arr[:rows]
        if r0 + rows < STRIP_ROWS:
            sim[r0 + rows:, x0:x0 + 16] = fills[fi][2][r0 + rows:, :]
    if not np.array_equal(sim, ter.strip):
        bad = np.argwhere(sim != ter.strip)
        raise SystemExit("make_world3_disk: the column plan does not reproduce the art's strip (first diff at row %d, x %d)" % tuple(bad[0]))
    add("plan", bytes(plan))
    facts["tiles"] = len(tiles)
    facts["bank"] = len(bank)

    # the BOB set: the lodge (intact, open), the AA nest (idle, tell, fire) and the 64 px pad, from the art's own generators
    def bob(name, frames, masked=True):
        arrs = [pad_to_words(f) for f in frames]
        h, w = frames[0].shape
        img = b"".join(planar_rows(a) for a in arrs)
        msk = b"".join(mask_rows(a) for a in arrs)
        add(name, img)
        if masked:
            add(name + "mask", msk)
        facts[name] = (frames[0].shape[1], h, len(frames), arrs[0].shape[1])
    bob("lodge", [BO.lodge(False), BO.lodge(True)], masked=False)   # (a plain copy, like the other barracks)
    bob("nest", [BO.aa_nest(0), BO.aa_nest(1), BO.aa_nest(2)])
    padp = pad_to_words(BO.pad(PAD_W))
    add("pad64", planar_rows(padp))
    facts["pad64"] = (PAD_W, PAD_ROWS, 1, padp.shape[1])

    blob = b""
    offs = {}
    for name, data in parts:
        if not name.startswith("pad_"):
            offs[name] = (len(blob), len(data))
        blob += data
    return blob, offs, facts


def world_header(offs, facts, L):
    o = ["#define W3_FAR_W %d" % FAR_W, "#define W3_FAR_H %d" % FAR_H, "#define W3_FAR_LOOP_W %d" % FAR_LOOP,
         "#define W3_STRIP_ROWS %d" % STRIP_ROWS, "#define W3_TILE_COUNT %d" % facts["tiles"], "#define W3_FILL_COUNT 8",
         "#define W3_MAP_COLS %d" % PILOT_COLS]
    for k in ("far", "tiletab", "tiles", "fills", "plan"):
        o.append("#define WORLD3_%s_OFFS %d" % (k.upper(), offs[k][0]))
    o.append("#define WORLD3_FILLS_BYTES %d" % offs["fills"][1])
    for k in ("lodge", "nest", "pad64"):
        w, h, fr, bw = facts[k]
        o.append("#define ART_W3_%s_W %d" % (k.upper(), w))
        o.append("#define ART_W3_%s_H %d" % (k.upper(), h))
        o.append("#define ART_W3_%s_FRAMES %d" % (k.upper(), fr))
        o.append("#define ART_W3_%s_BITMAP_W %d" % (k.upper(), bw))
        o.append("#define WORLD3_%s_OFFS %d" % (k.upper(), offs[k][0]))
        if k + "mask" in offs:
            o.append("#define WORLD3_%sMASK_OFFS %d" % (k.upper(), offs[k + "mask"][0]))
    total = max(a + b for a, b in offs.values())
    o.append("#define WORLD3_BYTES %d" % total)
    return "\n".join(o)


def main(argv):
    art = find_art(argv)
    L = load_art(art)
    ter, objects = pilot_terrain(art)
    blob, offs, facts = build_world(art, L, ter)
    files = {os.path.join("disk", "world3.bin"): blob,
             os.path.join("src", "world3_art.h"): header(L, world_header(offs, facts, L)).encode(),
             os.path.join("src", "world3_map.h"): map_header(ter, objects, L).encode()}
    stale = False
    for rel, data in files.items():
        p = os.path.join(root, rel)
        old = open(p, "rb").read() if os.path.exists(p) else None
        if old != data:
            stale = True
            if "--check" not in argv:
                open(p, "wb").write(data)
                print("wrote", rel, len(data))
    if "--check" in argv and stale:
        print("make_world3_disk: stale outputs")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
